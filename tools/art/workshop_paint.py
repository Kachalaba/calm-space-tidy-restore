"""Deterministic gouache painting primitives for the Calm Space workshop art.

Everything here is original, procedurally authored output. No third-party
image, texture, or brush asset is read, downloaded, or embedded. The module is
pure numpy + Pillow so the room art can be regenerated byte-identically from
source at any time.

Coordinate space is the portrait reference composition used by the runtime
CanvasScaler: 1080 x 2400, origin at the top-left corner.
"""

from __future__ import annotations

import numpy as np
from PIL import Image, ImageDraw, ImageFilter

WIDTH = 1080
HEIGHT = 2400
SUPERSAMPLE = 2

# Restrained sage / clay / cream palette with warm wood.
